constexpr std::wstring_view commandPrefix = L"powershell.exe -NoProfile -NonInteractive -EncodedCommand ";
constexpr std::wstring_view pipeSuffix = L"' --claude-statusline | Out-Null";

std::wstring Pipe(const wchar_t* input, const std::wstring& exe) {
    std::wstring script = std::wstring(input) + L" | & '";
    for (wchar_t c : exe) {
        if (c == L'\'') script += L"''";
        else script += c == L'\\' ? L'/' : c;
    }
    return script + std::wstring(pipeSuffix);
}

std::wstring Encode(const std::wstring& script) {
    auto* bytes = reinterpret_cast<const BYTE*>(script.data());
    DWORD bytesCount = static_cast<DWORD>(script.size() * sizeof(wchar_t));
    DWORD chars = 0;
    constexpr DWORD flags = CRYPT_STRING_BASE64 | CRYPT_STRING_NOCRLF;
    if (!CryptBinaryToStringW(bytes, bytesCount, flags, nullptr, &chars)) return {};
    std::wstring data(chars, L'\0');
    if (!CryptBinaryToStringW(bytes, bytesCount, flags, data.data(), &chars)) return {};
    data.resize(chars);
    return std::wstring(commandPrefix) + data;
}

std::wstring Decode(const std::string& command) {
    std::wstring text(command.begin(), command.end());
    if (text.compare(0, commandPrefix.size(), commandPrefix) != 0) return {};
    auto* data = text.c_str() + commandPrefix.size();
    DWORD bytes = 0;
    if (!CryptStringToBinaryW(data, 0, CRYPT_STRING_BASE64, nullptr, &bytes, nullptr, nullptr) ||
        bytes == 0 || bytes % sizeof(wchar_t) || bytes > 32768) return {};
    std::wstring script(bytes / sizeof(wchar_t), L'\0');
    if (!CryptStringToBinaryW(data, 0, CRYPT_STRING_BASE64, reinterpret_cast<BYTE*>(script.data()),
                             &bytes, nullptr, nullptr)) return {};
    return script;
}

// Recognize only the exact PowerShell command previously generated by Wireless Battery.
bool IsLegacy(std::wstring_view script) {
    constexpr std::wstring_view start = L"$input | & '";
    constexpr std::wstring_view legacyExe = L"/WirelessBattery.exe";
    if (script.size() <= start.size() + pipeSuffix.size() + legacyExe.size() ||
        script.substr(0, start.size()) != start ||
        script.substr(script.size() - pipeSuffix.size()) != pipeSuffix) return false;
    auto path = script.substr(start.size(), script.size() - start.size() - pipeSuffix.size());
    if (_wcsnicmp(path.data() + path.size() - legacyExe.size(), legacyExe.data(), legacyExe.size()) != 0)
        return false;
    if (path.size() < 3 || path[1] != L':' || path[2] != L'/') return false;
    for (size_t i = 0; i < path.size(); ++i) {
        if (path[i] < 32) return false;
        if (path[i] == L'\'' && (++i == path.size() || path[i] != L'\'')) return false;
    }
    return true;
}

struct Member {
    const char* begin = nullptr;
    const char* end = nullptr;
    const char* removeBegin = nullptr;
    const char* removeEnd = nullptr;
};

Member FindMember(json::Parser parser, const char* key) {
    parser.ws();
    if (parser.p == parser.e || *parser.p++ != '{') return {};
    const char* comma = nullptr;
    while (parser.p < parser.e) {
        parser.ws();
        const char* keyStart = parser.p;
        std::string name;
        if (parser.p == parser.e || *parser.p != '"' || !parser.parseString(name)) return {};
        parser.ws();
        if (parser.p == parser.e || *parser.p++ != ':') return {};
        parser.ws();
        const char* begin = parser.p;
        json::Json value;
        if (!parser.parse(value)) return {};
        const char* end = parser.p;
        parser.ws();
        const bool more = parser.p != parser.e && *parser.p == ',';
        if (name == key)
            return {begin, end, more || !comma ? keyStart : comma, more ? parser.p + 1 : end};
        if (!more) return {};
        comma = parser.p++;
    }
    return {};
}

std::string Ascii(const std::wstring& value) {
    // The PowerShell launcher and its Base64 argument are always ASCII.
    return std::string(value.begin(), value.end());
}

int Update(std::string& contents, const std::wstring& exe, bool enable) {
    size_t bom = contents.compare(0, 3, "\xef\xbb\xbf") == 0 ? 3 : 0;
    auto* start = contents.data() + bom;
    json::Parser parser{start, contents.data() + contents.size()};
    json::Json root;
    if (!parser.parse(root) || root.type != json::Json::Obj) return 3;
    const char* close = parser.p - 1;
    parser.ws();
    if (parser.p != parser.e) return 3;

    auto replace = [&](const char* begin, const char* end, const std::string& replacement) {
        contents.replace(begin - contents.data(), end - begin, replacement);
    };
    std::wstring self = Pipe(L"$input", exe);
    const auto* status = root.get("statusLine");
    if (!status) {
        if (!enable) return 0;
        auto encoded = Encode(self);
        if (encoded.empty()) return 4;
        std::string field = root.obj.empty() ? "" : ",";
        field += "\n  \"statusLine\": { \"type\": \"command\", \"command\": \"" + Ascii(encoded) + "\" }\n";
        const char* insert = close;
        while (insert > start && (insert[-1] == ' ' || insert[-1] == '\r' ||
                                   insert[-1] == '\n' || insert[-1] == '\t')) --insert;
        replace(insert, insert, field);
        return 0;
    }
    const auto* command = status->get("command");
    const auto* type = status->get("type");
    if (status->type != json::Json::Obj || !type || type->type != json::Json::Str || type->str != "command" ||
        !command || command->type != json::Json::Str) return 2;
    auto script = Decode(command->str);
    auto wrapper = L"$quota = $input | Out-String\n" + Pipe(L"$quota", exe) + L"\n";
    std::wstring legacy;
    if (script.compare(0, wrapper.size(), wrapper) == 0 &&
        script.compare(wrapper.size(), 6, L"$quota") == 0) {
        auto original = L"$input" + script.substr(wrapper.size() + 6);
        if (IsLegacy(original)) legacy = std::move(original);
    }

    auto member = FindMember({start, close + 1}, "statusLine");
    if (!member.begin) return 3;
    if (enable) {
        if (script == self || !legacy.empty()) return 0;
        if (!IsLegacy(script)) return 2;
        script = wrapper + L"$quota" + script.substr(6);
    } else {
        if (!legacy.empty()) script = legacy;
        else if (script == self && status->obj.size() == 2) {
            replace(member.removeBegin, member.removeEnd, "");
            return 0;
        } else return 2;
    }
    auto field = FindMember({member.begin, member.end}, "command");
    auto encoded = Encode(script);
    if (!field.begin || encoded.empty()) return 4;
    replace(field.begin, field.end, "\"" + Ascii(encoded) + "\"");
    return 0;
}

struct Handle {
    HANDLE value;
    ~Handle() { if (value != INVALID_HANDLE_VALUE) CloseHandle(value); }
};

std::wstring Environment(const wchar_t* name) {
    DWORD count = GetEnvironmentVariableW(name, nullptr, 0);
    if (!count) return {};
    std::wstring value(count, L'\0');
    DWORD read = GetEnvironmentVariableW(name, value.data(), count);
    value.resize(read < count ? read : 0);
    return value;
}

template<class Edit>
int UpdateFile(const std::wstring& directory, const wchar_t* filename, bool enable, Edit edit) {
    auto path = directory + L"\\" + filename;
    Handle input{CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_DELETE,
                                      nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr)};
    bool exists = input.value != INVALID_HANDLE_VALUE;
    std::string contents = "{}";
    if (exists) {
        LARGE_INTEGER size{};
        FILE_ATTRIBUTE_TAG_INFO info{};
        if (!GetFileInformationByHandleEx(input.value, FileAttributeTagInfo, &info, sizeof(info)) ||
            (info.FileAttributes & (FILE_ATTRIBUTE_DIRECTORY | FILE_ATTRIBUTE_REPARSE_POINT)) ||
            !GetFileSizeEx(input.value, &size) || size.QuadPart <= 0 || size.QuadPart > 16 * 1024 * 1024) return 3;
        contents.resize(static_cast<size_t>(size.QuadPart));
        DWORD got = 0;
        if (!ReadFile(input.value, contents.data(), static_cast<DWORD>(contents.size()), &got, nullptr) ||
            got != contents.size()) return 3;
    } else {
        DWORD error = GetLastError();
        if (error != ERROR_FILE_NOT_FOUND && error != ERROR_PATH_NOT_FOUND) return 3;
        if (!enable) return 0;
        if (!CreateDirectoryW(directory.c_str(), nullptr) && GetLastError() != ERROR_ALREADY_EXISTS) return 4;
    }

    auto original = contents;
    int result = edit(contents);
    if (result || contents == original) return result;
    wchar_t temp[MAX_PATH]{};
    if (!GetTempFileNameW(directory.c_str(), L"AUM", 0, temp)) return 4;
    bool written;
    {
        Handle output{CreateFileW(temp, GENERIC_WRITE, 0, nullptr, TRUNCATE_EXISTING,
                                           FILE_ATTRIBUTE_NORMAL, nullptr)};
        DWORD count = 0;
        written = output.value != INVALID_HANDLE_VALUE &&
            WriteFile(output.value, contents.data(), static_cast<DWORD>(contents.size()), &count, nullptr) &&
            count == contents.size() && FlushFileBuffers(output.value);
    }
    if (written && !exists && MoveFileExW(temp, path.c_str(), MOVEFILE_WRITE_THROUGH)) return 0;
    if (written && exists) {
        wchar_t backup[MAX_PATH]{};
        if (GetTempFileNameW(directory.c_str(), L"AUM", 0, backup) && DeleteFileW(backup)) {
            // Keep the existing file's security attributes and retain a recovery copy on failure.
            if (ReplaceFileW(path.c_str(), temp, backup, 0, nullptr, nullptr)) {
                DeleteFileW(backup);
                return 0;
            }
            if (GetFileAttributesW(path.c_str()) == INVALID_FILE_ATTRIBUTES)
                MoveFileExW(backup, path.c_str(), MOVEFILE_WRITE_THROUGH);
        }
    }
    DeleteFileW(temp);
    return 4;
}

enum class PriorTrust { Unmanaged, Missing, Denied };
constexpr char trustField[] = "hasTrustDialogAccepted";
constexpr wchar_t trustSubkey[] = L"Software\\AIUsageMonitor";
constexpr wchar_t trustValue[] = L"ManagedClaudeTrust";

std::string WorkspaceKey(std::wstring path) {
    std::replace(path.begin(), path.end(), L'\\', L'/');
    int length = WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS, path.data(),
                                     static_cast<int>(path.size()), nullptr, 0, nullptr, nullptr);
    if (!length) return {};
    std::string key(length, '\0');
    if (!WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS, path.data(),
                             static_cast<int>(path.size()), key.data(), length, nullptr, nullptr))
        return {};
    return key;
}

// Edit only the dedicated workspace entry. Preserve each unrelated project and setting verbatim.
int UpdateTrust(std::string& contents, const std::string& key, bool enable, PriorTrust& prior) {
    size_t bom = contents.compare(0, 3, "\xef\xbb\xbf") == 0 ? 3 : 0;
    const char* start = contents.data() + bom;
    json::Parser parser{start, contents.data() + contents.size()};
    json::Json root;
    if (!parser.parse(root) || root.type != json::Json::Obj) return 3;
    const char* close = parser.p;
    parser.ws();
    if (parser.p != parser.e) return 3;

    const auto* projects = root.get("projects");
    if (projects && projects->type != json::Json::Obj) return 3;
    const auto* project = projects ? projects->get(key.c_str()) : nullptr;
    if (project && project->type != json::Json::Obj) return 3;
    const auto* trust = project ? project->get(trustField) : nullptr;
    if (trust && trust->type != json::Json::Bool) return 3;
    if (enable && trust && trust->num) return 0;
    if (!enable && (!trust || !trust->num || prior == PriorTrust::Unmanaged)) return 0;

    auto projectsSpan = FindMember({start, close}, "projects");
    auto projectSpan = projectsSpan.begin ? FindMember({projectsSpan.begin, projectsSpan.end}, key.c_str()) : Member{};
    auto trustSpan = projectSpan.begin ? FindMember({projectSpan.begin, projectSpan.end}, trustField) : Member{};
    if ((projects && !projectsSpan.begin) || (project && !projectSpan.begin) || (trust && !trustSpan.begin))
        return 3;

    if (trust) {
        if (!enable && prior == PriorTrust::Missing) {
            contents.erase(trustSpan.removeBegin - contents.data(), trustSpan.removeEnd - trustSpan.removeBegin);
        } else {
            contents.replace(trustSpan.begin - contents.data(), trustSpan.end - trustSpan.begin,
                             enable ? "true" : "false");
            if (enable) prior = PriorTrust::Denied;
        }
        return 0;
    }

    std::string field = std::string("\"") + trustField + "\":true";
    if (!project) field = "\"" + key + "\":{" + field + "}";
    if (!projects) field = "\"projects\":{" + field + "}";
    const auto* parent = project ? project : projects ? projects : &root;
    const char* end = project ? projectSpan.end : projects ? projectsSpan.end : close;
    if (!parent->obj.empty()) field.insert(0, ",");
    contents.insert(end - 1 - contents.data(), field);
    prior = PriorTrust::Missing;
    return 0;
}

