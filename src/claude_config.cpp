constexpr std::wstring_view commandPrefix = L"powershell.exe -NoProfile -NonInteractive -EncodedCommand ";
constexpr std::wstring_view pipeSuffix = L"' --claude-statusline | Out-Null";

std::wstring Pipe(const wchar_t* input, const std::wstring& exe) {
    std::wstring script = std::wstring(input) + L" | & '";
    for (wchar_t c : exe) {
        if (c == L'\'') script += L"''";
        else script += c == L'\\' ? L'/' : c;
    }
    return script + std::wstring(pipeSuffix);
}

std::wstring Encode(const std::wstring& script) {
    auto* bytes = reinterpret_cast<const BYTE*>(script.data());
    DWORD bytesCount = static_cast<DWORD>(script.size() * sizeof(wchar_t));
    DWORD chars = 0;
    constexpr DWORD flags = CRYPT_STRING_BASE64 | CRYPT_STRING_NOCRLF;
    if (!CryptBinaryToStringW(bytes, bytesCount, flags, nullptr, &chars)) return {};
    std::wstring data(chars, L'\0');
    if (!CryptBinaryToStringW(bytes, bytesCount, flags, data.data(), &chars)) return {};
    data.resize(chars);
    return std::wstring(commandPrefix) + data;
}

std::wstring Decode(const std::string& command) {
    std::wstring text(command.begin(), command.end());
    if (text.compare(0, commandPrefix.size(), commandPrefix) != 0) return {};
    auto* data = text.c_str() + commandPrefix.size();
    DWORD bytes = 0;
    if (!CryptStringToBinaryW(data, 0, CRYPT_STRING_BASE64, nullptr, &bytes, nullptr, nullptr) ||
        bytes == 0 || bytes % sizeof(wchar_t) || bytes > 32768) return {};
    std::wstring script(bytes / sizeof(wchar_t), L'\0');
    if (!CryptStringToBinaryW(data, 0, CRYPT_STRING_BASE64, reinterpret_cast<BYTE*>(script.data()),
                             &bytes, nullptr, nullptr)) return {};
    return script;
}

// Recognize only the exact PowerShell command previously generated by Wireless Battery.
bool IsLegacy(std::wstring_view script) {
    constexpr std::wstring_view start = L"$input | & '";
    constexpr std::wstring_view legacyExe = L"/WirelessBattery.exe";
    if (script.size() <= start.size() + pipeSuffix.size() + legacyExe.size() ||
        script.substr(0, start.size()) != start ||
        script.substr(script.size() - pipeSuffix.size()) != pipeSuffix) return false;
    auto path = script.substr(start.size(), script.size() - start.size() - pipeSuffix.size());
    if (_wcsnicmp(path.data() + path.size() - legacyExe.size(), legacyExe.data(), legacyExe.size()) != 0)
        return false;
    if (path.size() < 3 || path[1] != L':' || path[2] != L'/') return false;
    for (size_t i = 0; i < path.size(); ++i) {
        if (path[i] < 32) return false;
        if (path[i] == L'\'' && (++i == path.size() || path[i] != L'\'')) return false;
    }
    return true;
}

struct Member {
    const char* begin = nullptr;
    const char* end = nullptr;
    const char* removeBegin = nullptr;
    const char* removeEnd = nullptr;
};

Member FindMember(json::Parser parser, const char* key) {
    parser.ws();
    if (parser.p == parser.e || *parser.p++ != '{') return {};
    const char* comma = nullptr;
    while (parser.p < parser.e) {
        parser.ws();
        const char* keyStart = parser.p;
        std::string name;
        if (parser.p == parser.e || *parser.p != '"' || !parser.parseString(name)) return {};
        parser.ws();
        if (parser.p == parser.e || *parser.p++ != ':') return {};
        parser.ws();
        const char* begin = parser.p;
        json::Json value;
        if (!parser.parse(value)) return {};
        const char* end = parser.p;
        parser.ws();
        const bool more = parser.p != parser.e && *parser.p == ',';
        if (name == key)
            return {begin, end, more || !comma ? keyStart : comma, more ? parser.p + 1 : end};
        if (!more) return {};
        comma = parser.p++;
    }
    return {};
}

std::string Ascii(const std::wstring& value) {
    // The PowerShell launcher and its Base64 argument are always ASCII.
    return std::string(value.begin(), value.end());
}

int Update(std::string& contents, const std::wstring& exe, bool enable) {
    size_t bom = contents.compare(0, 3, "\xef\xbb\xbf") == 0 ? 3 : 0;
    auto* start = contents.data() + bom;
    json::Parser parser{start, contents.data() + contents.size()};
    json::Json root;
    if (!parser.parse(root) || root.type != json::Json::Obj) return 3;
    const char* close = parser.p - 1;
    parser.ws();
    if (parser.p != parser.e) return 3;

    auto replace = [&](const char* begin, const char* end, const std::string& replacement) {
        contents.replace(begin - contents.data(), end - begin, replacement);
    };
    std::wstring self = Pipe(L"$input", exe);
    const auto* status = root.get("statusLine");
    if (!status) {
        if (!enable) return 0;
        auto encoded = Encode(self);
        if (encoded.empty()) return 4;
        std::string field = root.obj.empty() ? "" : ",";
        field += "\n  \"statusLine\": { \"type\": \"command\", \"command\": \"" + Ascii(encoded) + "\" }\n";
        const char* insert = close;
        while (insert > start && (insert[-1] == ' ' || insert[-1] == '\r' ||
                                   insert[-1] == '\n' || insert[-1] == '\t')) --insert;
        replace(insert, insert, field);
        return 0;
    }
    const auto* command = status->get("command");
    const auto* type = status->get("type");
    if (status->type != json::Json::Obj || !type || type->type != json::Json::Str || type->str != "command" ||
        !command || command->type != json::Json::Str) return 2;
    auto script = Decode(command->str);
    auto wrapper = L"$quota = $input | Out-String\n" + Pipe(L"$quota", exe) + L"\n";
    std::wstring legacy;
    if (script.compare(0, wrapper.size(), wrapper) == 0 &&
        script.compare(wrapper.size(), 6, L"$quota") == 0) {
        auto original = L"$input" + script.substr(wrapper.size() + 6);
        if (IsLegacy(original)) legacy = std::move(original);
    }

    auto member = FindMember({start, close + 1}, "statusLine");
    if (!member.begin) return 3;
    if (enable) {
        if (script == self || !legacy.empty()) return 0;
        if (!IsLegacy(script)) return 2;
        script = wrapper + L"$quota" + script.substr(6);
    } else {
        if (!legacy.empty()) script = legacy;
        else if (script == self && status->obj.size() == 2) {
            replace(member.removeBegin, member.removeEnd, "");
            return 0;
        } else return 2;
    }
    auto field = FindMember({member.begin, member.end}, "command");
    auto encoded = Encode(script);
    if (!field.begin || encoded.empty()) return 4;
    replace(field.begin, field.end, "\"" + Ascii(encoded) + "\"");
    return 0;
}

struct Handle {
    HANDLE value;
    ~Handle() { if (value != INVALID_HANDLE_VALUE) CloseHandle(value); }
};

std::wstring Environment(const wchar_t* name) {
    DWORD count = GetEnvironmentVariableW(name, nullptr, 0);
    if (!count) return {};
    std::wstring value(count, L'\0');
    DWORD read = GetEnvironmentVariableW(name, value.data(), count);
    value.resize(read < count ? read : 0);
    return value;
}

